// Валюты, в которых может вестись кошелёк и позиция капитала. Тенге —
// «домашняя»: в ней ведётся вся семья и бизнес, и только тенговые суммы
// складываются между собой на главном экране (см. App.jsx). Юань нужен для
// Alipay, доллар — для наличных USD.
//
// Добавить новую валюту = дописать сюда, в frontend/src/currencies.js и в
// CHECK-констрейнты в db.js. Список намеренно короткий: каждая валюта —
// это ещё один курс, который кто-то должен руками вписывать в снимок
// капитала, иначе итог посчитается неправильно.
export const CURRENCIES = ["KZT", "USD", "CNY"];

export const HOME_CURRENCY = "KZT";

export function isValidCurrency(currency) {
  return CURRENCIES.includes(currency);
}
